#!/usr/bin/env python3
"""Check every encounter definition (data/encounters/**/*.json) against the client tables and the researched creature data.

Ability names: a name is confirmed by the tables when a Spell4 row with that spell name has a designer description naming the boss
("[STL] e314 - (N/V) Stormtalon - Static Wave - Base"), and confirmed by observation when Jabbithole saw the creature cast a spell with
that name (data/research/creature-abilities.tsv). A guide or boss mod name plus one of these is two sources: names "certain";
some names confirmed: "partial"; none: "guess". Timer confidence comes from scripts/research/bossmod_timers.py ("confidence").

Writes the "names" field into the files and docs/ENCOUNTER-SOURCES.md (one row per boss). Prints a summary of at most 30 lines.
"""
import glob, json, os, re, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, HERE)
from tbl import load, text


def slug(s):
    return re.sub(r'[^a-z0-9]+', '', (s or '').lower())


TAG = re.compile(r'^\[(?P<tag>[A-Z0-9]{2,4})\]\s*e(?P<enc>\d+)\s*-\s*(?:\((?P<mode>[NV/]+)\)\s*)?(?P<boss>[^-]+?)\s*-\s*(?P<rest>.*)$')


def main():
    bases = {r['ID']: slug(text(r['localizedTextIdName'])) for r in load('Spell4Base')}
    by_name = defaultdict(list)          # spell name slug -> descriptions
    enc_of = {}                          # spell4 id -> designer encounter id (the e### in "[GA] e412 - Genetic Architect - ...")
    for r in load('Spell4'):
        desc = r['description'] or ''
        by_name[bases.get(r['spell4BaseIdBaseSpell'], '')].append(desc)
        m = TAG.match(desc.replace('[Dungeon]', ''))
        if m:
            enc_of[r['ID']] = m.group('enc')
    observed = defaultdict(set)          # creature name slug -> spell name slugs
    encounters = defaultdict(set)        # creature name slug -> designer encounter ids of the spells it was seen casting
    for line in open(os.path.join(ROOT, 'data', 'research', 'creature-abilities.tsv'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) >= 5:
            observed[slug(f[0])].add(slug(f[4]))
            if f[3].isdigit() and int(f[3]) in enc_of:
                encounters[slug(f[0])].add(enc_of[int(f[3])])

    rows, stats = [], defaultdict(int)
    for path in sorted(glob.glob(os.path.join(ROOT, 'data', 'encounters', '**', '*.json'), recursive=True)):
        data = json.load(open(path))
        single = isinstance(data, dict)
        defs = [data] if single else data
        for d in defs:
            boss = d['boss']
            boss_words = [w.lower() for w in re.findall(r"[A-Za-z'-]{4,}", boss)]
            names = sorted({a['spell'] for p in d['phases'] for a in p['abilities'] if not a['spell'].isdigit()})
            table_ok, seen_ok, missing = [], [], []
            for n in names:
                descs = by_name.get(slug(n), [])
                # the designer description names the boss, or carries the encounter id of spells the boss was seen casting
                in_table = any(any(w in desc.lower() for w in boss_words) or
                               ((m := TAG.match(desc.replace('[Dungeon]', ''))) and m.group('enc') in encounters.get(slug(boss), ()))
                               for desc in descs)
                in_seen = slug(n) in observed.get(slug(boss), set())
                if in_table:
                    table_ok.append(n)
                if in_seen:
                    seen_ok.append(n)
                if not in_table and not in_seen:
                    missing.append(n)
            confirmed = len(names) - len(missing)
            generated_ids = not names
            verdict = 'tables (spell ids)' if generated_ids else 'certain' if names and not missing else 'partial' if confirmed else 'guess'
            d['names'] = verdict
            stats[verdict] += 1
            rel = os.path.relpath(path, ROOT)
            rows.append((rel, boss, d.get('world', 0), (d.get('source') or 'hand written')[:70], f'{confirmed}/{len(names)}',
                         len(table_ok), len(seen_ok), verdict, d.get('confidence', 'guess'), ', '.join(missing)[:80]))
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data if single else defs, f, indent=1, ensure_ascii=False)
            f.write('\n')

    out = os.path.join(ROOT, 'docs', 'ENCOUNTER-SOURCES.md')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('# Encounter sources and confidence\n\n'
                'Generated by `scripts/research/encounter_audit.py` (names) and `scripts/research/bossmod_timers.py` (timers). '
                'Names: a guide/boss-mod ability name confirmed by the Spell4 designer descriptions naming the boss or by Jabbithole casts '
                '(certain = all confirmed). Timers: likely = RaidCore and DruseraBossMods (or LUI where it differs from RaidCore) agree within '
                'max(5 s, 15 %) for half or more of the abilities, guess = assumption (no boss mod or guide gives a number). '
                'Bosses without a file use the generated default (researched abilities, filtered by the designer tags, timers assumed).\n\n'
                '| file | boss | world | source | names confirmed | by tables | by casts | names | timers | unconfirmed names |\n'
                '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n')
        for r in rows:
            f.write('| ' + ' | '.join(str(x).replace('|', '/') for x in r) + ' |\n')
    print(f'{len(rows)} definitions, names: {dict(stats)}')
    timers = defaultdict(int)
    for r in rows:
        timers[r[8]] += 1
    print(f'timers: {dict(timers)}')
    print('unconfirmed names (hand written files):')
    for r in [r for r in rows if r[9] and '/raidcore/' not in r[0]][:20]:
        print(f'  {r[1]}: {r[9]}')


main()
