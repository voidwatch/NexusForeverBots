#!/usr/bin/env python3
"""docs/INSTANCES.md from scripts/instance-run.sh results: instances_md.py RUNDIR [NOTES.tsv]
RUNDIR/instances.tsv rows come from scripts/research/instance_table.py (the last row per world wins). NOTES.tsv: world<TAB>reason text,
written by hand after reading the stalled/remaining columns (the reason a run did not clear, or what was fixed)."""
import collections, glob, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tbl  # noqa: E402

run = sys.argv[1]
notes = {}
if len(sys.argv) > 2 and os.path.exists(sys.argv[2]):
    for l in open(sys.argv[2], encoding='utf-8'):
        if '\t' in l and not l.startswith('#'):
            w, t = l.rstrip('\n').split('\t', 1)
            notes[int(w)] = t
rows = {}
for l in open(os.path.join(run, 'instances.tsv'), encoding='utf-8'):
    f = l.rstrip('\n').split('\t')
    if len(f) >= 14:
        rows[int(f[0])] = f
kind = {1: 'shiphand', 6: 'adventure', 9: 'raid', 11: 'dungeon'}
world = tbl.index('World')
defs = collections.Counter()
for p in glob.glob('data/encounters/*/*.json'):
    d = json.load(open(p))
    for e in (d if isinstance(d, list) else [d]):
        defs[e.get('world')] += 1

out = ['# Instances: bot-team runs', '',
       f'Generated by `scripts/research/instances_md.py {run}` from `scripts/instance-run.sh` batches (8 worlds at once, one team per world,',
       'teams rotate to the next world after a clear, at most 35 minutes per batch). Bots are immortal (NF_BOTS_IMMORTAL=1), so wipes do not',
       'happen; a clear means the team killed every hostile creature it could reach, or every boss with an encounter after at least one fell.',
       'Team level = the highest level among the bosses with an encounter definition, else the median creature level.',
       '"bosses" = distinct creatures with an encounter controller (hand written, RaidCore or generated from the tables) killed in the batch.', '',
       '| world | name | type | team | entered | cleared | best clear | bosses killed | hand/RaidCore scripts | result / reason |',
       '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
results = collections.Counter()
order = sorted(rows, key=lambda w: (['dungeon', 'shiphand', 'adventure', 'raid'].index(kind.get(world[w]['type'], 'dungeon')) if w in world else 9, w))
for w in order:
    f = rows[w]
    e = world.get(w, {})
    name = (e.get('assetPath') or '').replace('Map\\', '')
    cleared = int(f[4])
    bosses = int(f[7] or 0)
    # a run that ended with nothing hostile left but no boss killed is "no boss", not a clear
    if cleared and bosses == 0:
        result, cleared = 'no boss (everything hostile killed, no boss died)', 0
    else:
        result = 'cleared' if cleared else ('empty (no hostile spawn)' if 'dungeon-empty' in f[12] else 'not cleared')
    results[result.split(' (')[0].split(':')[0]] += 1
    reason = notes.get(w, '')
    if not reason and not cleared and bosses == 0 and 'no boss' not in result or (not reason and result == 'not cleared'):
        reason = (f[11] or f[10])[:160]
    out.append(f'| {w} | {name} | {kind.get(e.get("type"), e.get("type"))} | {f[1]} | {f[3]} | {cleared} | {(f[9] or "-") if cleared else "-"} | {f[7]} | '
               f'{defs.get(w, 0)} | {result}{": " + reason if reason else ""} |')
out.append('')
out.insert(8, 'Totals: ' + ', '.join(f'{k} {v}' for k, v in sorted(results.items())) + f' of {len(rows)} worlds. "cleared" needs at least one boss killed.')
out.insert(9, '')
open('docs/INSTANCES.md', 'w').write('\n'.join(out) + '\n')
print(f'{len(rows)} worlds: ' + ', '.join(f'{k} {v}' for k, v in sorted(results.items())))
