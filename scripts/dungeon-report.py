#!/usr/bin/env python3
"""Turns the newest soak/dungeon-sweep/*/summary.txt into docs/DUNGEONS.md (one row per world: team, spawns, runs entered, clears, boss kills)."""
import glob, re, sys

files = sorted(glob.glob('soak/dungeon-sweep/*/summary.txt'))
if not files:
    sys.exit('no sweep found')
txt = open(files[-1]).read()
rows, skipped = [], []
for m in re.finditer(r'world (\d+): only (\d+) spawns, skipped', txt):
    skipped.append(f'{m.group(1)} ({m.group(2)} spawns)')
for b in re.split(r'(?m)^== world ', txt)[1:]:
    w = re.match(r'(\d+) team (\d+) \((\d+) spawns\), (\d+) minutes', b.split('\n')[0])
    if not w:
        continue
    world, team, spawns, mins = w.groups()
    entered = re.search(r'(\d+)x world %s team of \d+ \[run \d+, attempt 1, level (\d+)' % world, b)
    cleared = sum(int(x) for x in re.findall(r'(\d+)x world %s team of \d+ \[run \d+, \d+ s' % world, b))
    bosses = sum(int(x) for x in re.findall(r'(\d+)x [^\n]*\(entity', b))
    problems = []
    if 'dungeon-enter-failed' in b:
        problems.append('team could not enter')
    if 'map-update-exception' in b:
        problems.append('map file missing')
    if 'encounter-spell-unresolved' in b:
        problems.append('boss spell names not in the data')
    if 'encounter-cast-exception' in b:
        problems.append('boss cast exception')
    rows.append(f'| {world} | {team} | {spawns} | {mins} | {entered.group(1) if entered else 0} (level {entered.group(2) if entered else "-"}) | {cleared} | {bosses} | {", ".join(problems) or "-"} |')

out = ['# Dungeon, expedition, adventure and raid runs by bot teams', '',
       f'Generated by `scripts/dungeon-report.py` from {files[-1]} (`scripts/dungeon-sweep.sh`). Bots are immortal (they cannot wipe), a team enters, fights everything hostile until nothing is left, leaves, waits for the reset and goes again. Clears need nothing hostile alive for 6 s (or all bosses dead after at least one fell); 10 minutes per dungeon and 20 per raid is often not enough to clear a whole instance.', '',
       '| world | team | spawns | minutes | runs entered | clears | boss fights won | problems |', '| --- | --- | --- | --- | --- | --- | --- | --- |'] + rows
out += ['', 'Skipped for lack of spawn data: ' + (', '.join(skipped) or 'none') + '.', '']
open('docs/DUNGEONS.md', 'w').write('\n'.join(out))
print(len(rows), 'worlds')
